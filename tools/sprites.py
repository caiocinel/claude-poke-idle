"""Convert Gen 1 sprites (64x64 PNG) into compact palette-encoded strings for the mod.

Usage: python -I tools/sprites.py <raw_dir> <out_js> [preview_png]
Each sprite becomes "w,h,palette_hex...,base64(4-bit indices)"; index 0 is transparent.
"""
import base64, sys
from PIL import Image

MAX = 30  # max pixel size of the longest side (half-block rows = MAX/2)

def load(path):
    im = Image.open(path).convert('RGBA')
    bbox = im.getbbox()
    if not bbox:
        return None
    im = im.crop(bbox)
    w, h = im.size
    f = min(1.0, MAX / max(w, h))
    if f < 1:
        nw, nh = max(1, round(w * f)), max(1, round(h * f))
        # Downscale with a majority filter so outlines survive better than plain nearest
        src = im.load()
        out = Image.new('RGBA', (nw, nh))
        dst = out.load()
        for y in range(nh):
            for x in range(nw):
                x0, x1 = int(x / f), max(int(x / f) + 1, int((x + 1) / f))
                y0, y1 = int(y / f), max(int(y / f) + 1, int((y + 1) / f))
                counts, opaque = {}, 0
                for yy in range(y0, min(y1, h)):
                    for xx in range(x0, min(x1, w)):
                        p = src[xx, yy]
                        if p[3] < 128:
                            continue
                        opaque += 1
                        counts[p[:3]] = counts.get(p[:3], 0) + 1
                total = (min(y1, h) - y0) * (min(x1, w) - x0)
                if opaque * 2 < total or not counts:
                    dst[x, y] = (0, 0, 0, 0)
                else:
                    # darkest color wins ties to keep outlines
                    c = max(counts.items(), key=lambda kv: (kv[1], -sum(kv[0])))[0]
                    dst[x, y] = (*c, 255)
        im = out
    return im

def encode(im):
    w, h = im.size
    px = im.load()
    palette, idx = [], []
    for y in range(h):
        for x in range(w):
            p = px[x, y]
            if p[3] < 128:
                idx.append(0)
                continue
            c = p[:3]
            if c not in palette:
                palette.append(c)
            idx.append(palette.index(c) + 1)
    if len(palette) > 15:
        # quantize: map extra colors to nearest of the first 15
        base = palette[:15]
        def near(c):
            return min(range(15), key=lambda i: sum((a - b) ** 2 for a, b in zip(base[i], c))) + 1
        idx = [i if i <= 15 else near(palette[i - 1]) for i in idx]
        palette = base
    if len(idx) % 2:
        idx.append(0)
    packed = bytes((idx[i] << 4) | idx[i + 1] for i in range(0, len(idx), 2))
    pal = ''.join('%02x%02x%02x' % c for c in palette)
    return f"{w},{h},{pal},{base64.b64encode(packed).decode()}"

def main():
    raw, out = sys.argv[1], sys.argv[2]
    front, back = [], []
    previews = []
    for i in range(1, 152):
        f = load(f'{raw}/front/{i}.png')
        b = load(f'{raw}/back/{i}.png')
        front.append(encode(f))
        back.append(encode(b))
        previews.append(f)
    with open(out, 'w', encoding='utf-8') as fh:
        fh.write('// Generated by tools/sprites.py from PokeAPI FireRed/LeafGreen sprites. Do not edit.\n')
        fh.write('export const FRONT = ' + repr(front).replace("'", '"') + '\n')
        fh.write('export const BACK = ' + repr(back).replace("'", '"') + '\n')
    if len(sys.argv) > 3:
        sheet = Image.new('RGBA', (MAX * 16, MAX * 10), (40, 40, 40, 255))
        for n, im in enumerate(previews):
            sheet.paste(im, ((n % 16) * MAX, (n // 16) * MAX), im)
        sheet.resize((sheet.width * 3, sheet.height * 3), Image.NEAREST).save(sys.argv[3])

main()
